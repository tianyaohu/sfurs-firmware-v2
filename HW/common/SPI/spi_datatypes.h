/*
 * spi_datatypes.h
 */
#ifndef SPI_DATATYPES_H
#define SPI_DATATYPES_H

#include "stm32h7xx_hal.h"
#include <stdint.h>

/*
 * Helper Macros
 */
#define SPI_U32_FROM_PAYLOAD(p) (((uint32_t)((p)[0])) | ((uint32_t)((p)[1]) << 8))

/*
 * SPI CHIP SELECT PINS
 */
#define SPI_OPTICAL_FLOW_CHIP_SELECT_PIN  GPIO_PIN_9
#define SPI_OPTICAL_FLOW_CHIP_SELECT_GPIO GPIOB
/*
 * SPI OPTICAL FLOW REGISTERS
 */
#define SPI_OPTICAL_FLOW_REGISTER_PRODUCT_ID          0x00U
#define SPI_OPTICAL_FLOW_REGISTER_REVISION_ID         0x01U
#define SPI_OPTICAL_FLOW_REGISTER_MOTION              0x02U
#define SPI_OPTICAL_FLOW_REGISTER_DELTA_X_L           0x03U
#define SPI_OPTICAL_FLOW_REGISTER_DELTA_X_H           0x04U
#define SPI_OPTICAL_FLOW_REGISTER_DELTA_Y_L           0x05U
#define SPI_OPTICAL_FLOW_REGISTER_DELTA_Y_H           0x06U
#define SPI_OPTICAL_FLOW_REGISTER_SQUAL               0x07U
#define SPI_OPTICAL_FLOW_REGISTER_RAWDATA_SUM         0x08U
#define SPI_OPTICAL_FLOW_REGISTER_MAXIMUM_RAWDATA     0x09U
#define SPI_OPTICAL_FLOW_REGISTER_MINIMUM_RAWDATA     0x0AU
#define SPI_OPTICAL_FLOW_REGISTER_SHUTTER_LOWER       0x0BU
#define SPI_OPTICAL_FLOW_REGISTER_SHUTTER_UPPER       0x0CU
#define SPI_OPTICAL_FLOW_REGISTER_OBSERVATION         0x15U
#define SPI_OPTICAL_FLOW_REGISTER_MOTION_BURST        0x16U
#define SPI_OPTICAL_FLOW_REGISTER_POWER_UP_RESET      0x3AU
#define SPI_OPTICAL_FLOW_REGISTER_SHUTDOWN            0x3BU
#define SPI_OPTICAL_FLOW_REGISTER_RESOLUTION          0x4EU
#define SPI_OPTICAL_FLOW_REGISTER_RAWDATA_GRAB        0x58U
#define SPI_OPTICAL_FLOW_REGISTER_RAWDATA_GRAB_STATUS 0x59U
#define SPI_OPTICAL_FLOW_REGISTER_ORIENTATION         0x5BU
#define SPI_OPTICAL_FLOW_REGISTER_INVERSE_PRODUCT_ID  0x5FU

#define SPI_OPTICAL_FLOW_BURST_LENGTH 12U

#define PAA5100_PRODUCT_ID_VALUE         0x49U
#define PAA5100_INVERSE_PRODUCT_ID_VALUE 0xB6U

#define COUNTS_TO_MM(p) (p * 0.0417079401491059)

typedef struct {
    int32_t delta_x;
    int32_t delta_y;
} SPI_OPTICAL_FLOW_DELTA_DATA_t;

HAL_StatusTypeDef spi_optical_flow_init(SPI_HandleTypeDef *spi_pointer);
HAL_StatusTypeDef spi_optical_flow_get_delta(SPI_HandleTypeDef *spi_pointer,
                                             SPI_OPTICAL_FLOW_DELTA_DATA_t *delta_data);

#endif
