static void relative(double got, double want) {
  if (want == 0)
    CHECK_EQ(got == 0, 1);
  else
    CHECK_NEAR(got, want, fabs(want) * 1e-9);
}

static int64_t round_even(double x) {
  double lo = floor(x), rem = x - lo;
  return (int64_t)(lo + (rem > 0.5 || (rem == 0.5 && fmod(lo, 2) != 0)));
}

static int64_t floor_div(int64_t x, int64_t divisor) {
  return x / divisor - (x % divisor < 0);
}

static void simulate(capture_sample *out, size_t n, size_t pre,
                     double r, double ell, double vbus, int64_t kp, int64_t ki,
                     double hold_a, double step_a, double v_off, int delay) {
  CHECK(delay >= 0 && delay <= 2);
  double t = 1.0 / CAPTURE_PWM_HZ;
  double vs = capture_volts_per_s16(vbus), cur = hold_a;
  int64_t integral = round_even(((r * hold_a + v_off) / vs) * CAPTURE_TF_KIDIV);
  int64_t pending[3] = {0};
  for (int j = 0; j < delay; ++j)
    pending[j] = round_even((r * hold_a + v_off) / vs);
  for (size_t k = 0; k < n; ++k) {
    double ref = k >= pre ? step_a : hold_a;
    int64_t meas = round_even(cur * CAPTURE_COUNTS_PER_AMP);
    int64_t ref_count = round_even(ref * CAPTURE_COUNTS_PER_AMP);
    int64_t err = ref_count - meas;
    integral += ki * err;
    int64_t vd = floor_div(kp * err, CAPTURE_TF_KPDIV) + floor_div(integral, CAPTURE_TF_KIDIV);
    if (vd > 32767) vd = 32767;
    if (vd < -32767) vd = -32767;
    out[k] = (capture_sample){(int32_t)meas, (int32_t)vd, (int32_t)ref_count};
    pending[delay] = vd;
    double applied = pending[0] * vs;
    for (int j = 0; j < delay; ++j)
      pending[j] = pending[j + 1];
    cur += t / ell * (applied - r * cur - v_off);
  }
}

static void check(double r, double ell, int64_t kp, int64_t ki, int delay) {
  capture_sample s[512];
  simulate(s, ARRAY_LEN(s), 64, r, ell, 12.1, kp, ki, 1, 3, 0.15, delay);
  capture_result a;
  CHECK_EQ(capture_analyze(1210, s, ARRAY_LEN(s), 64, CAPTURE_PWM_HZ, &a), CAPTURE_OK);
  CHECK_NEAR(a.r_ohm, r, 0.03 * r);
  CHECK_NEAR(a.l_h, ell, 0.1 * ell);
  CHECK_EQ(a.delay_periods, delay);
  CHECK_NEAR(a.hold_a, 1, 0.01);
  CHECK_NEAR(a.step_a, 3, 0.01);
  CHECK(fabs(a.steady_error_a) < 0.02);
}

