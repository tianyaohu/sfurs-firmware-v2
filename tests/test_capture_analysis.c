static void compare_result(const capture_result *a, const capture_result *b) {
#define FIELD(f) relative(a->f, b->f)
  FIELD(vbus_v); FIELD(hold_a); FIELD(step_a); FIELD(r_ohm); FIELD(l_h);
  FIELD(tau_ms); FIELD(v_offset); FIELD(rise_us); FIELD(overshoot_pct);
  FIELD(settle_us); FIELD(steady_error_a); FIELD(noise_a); FIELD(settle_band_a);
#undef FIELD
  CHECK_EQ(a->delay_periods, b->delay_periods);
  CHECK_EQ(a->disturbance_samples, b->disturbance_samples);
}

